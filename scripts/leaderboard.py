"""Builds results/RESULTS.md from results/runs/*.csv (unsupervised runs + their LB score).
If RESULTS.md has a merge conflict: just rerun this script."""
import glob
import pandas as pd

fs = sorted(glob.glob("results/runs/*.csv"))
if not fs:
    raise SystemExit("no runs yet")
df = pd.concat([pd.read_csv(f) for f in fs])
df["lb_num"] = pd.to_numeric(df["lb"], errors="coerce")
df = df.sort_values(["lb_num", "time"], na_position="last").drop(columns="lb_num")


def md(d):
    d = d.fillna("")
    return "\n".join(["| " + " | ".join(d.columns) + " |", "|" + "---|" * len(d.columns)]
                     + ["| " + " | ".join(str(v) for v in r) + " |" for r in d.values])


open("results/RESULTS.md", "w").write(
    "# Results\n\nUnsupervised: every run is a submission. `lb` = HFactory score, filled by hand after upload.\n"
    "Sorted by `lb` ascending: CHECK the metric direction (lower is better for RMSE/MAE, higher for correlation).\n"
    "Generated by `python scripts/leaderboard.py`. Do not edit by hand.\n\n" + md(df) + "\n")
print(df.to_string(index=False))
