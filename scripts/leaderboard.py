"""Aggregates results/scores/*.csv into results/RESULTS.md (best run per track + all runs).
If RESULTS.md has a merge conflict: just rerun this script."""
import glob
import pandas as pd

fs = sorted(glob.glob("results/scores/*.csv"))
if not fs:
    raise SystemExit("no results yet")
df = pd.concat([pd.read_csv(f) for f in fs]).sort_values("rmse_mean")
cols = ["track", "experiment", "who", "rmse_mean", "rmse_valence", "rmse_arousal", "r_valence", "r_arousal", "lb", "time", "notes"]
best = df.groupby("track").head(1)[cols]


def md(d):
    d = d.fillna("")
    return "\n".join(["| " + " | ".join(d.columns) + " |", "|" + "---|" * len(d.columns)]
                     + ["| " + " | ".join(str(v) for v in r) + " |" for r in d.values])


open("results/RESULTS.md", "w").write(
    "# Results\n\nPrimary metric: `rmse_mean` (lower is better) on the shared 5 folds, until the official metric is known.\n"
    "Generated by `python scripts/leaderboard.py`. Do not edit by hand.\n\n"
    f"## Best run per track\n\n{md(best)}\n\n## All runs\n\n{md(df[cols])}\n")
print(best.to_string(index=False))
