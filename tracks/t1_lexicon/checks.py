"""t1_lexicon: label-free checks of the lexicon estimators + figures (tracks/t1_lexicon/figs/).
1. Agreement between variants (Pearson, test set).
2. Noise vs length: spread of nrc_*_mean by number of matched words (why shrinkage).
3. Sanity: arousal should rise with exclamations / high-arousal context; valence with negations?
4. Per-parliament and per-year means (plausible? used by the time-series product).
5. Valence vs arousal: U-shape? (DimStance, Slavic parliaments)
6. Italian set: same distribution?
Usage: python tracks/t1_lexicon/checks.py"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

from src.common import RES, agreement, load

OUT = Path(__file__).parent / "figs"
OUT.mkdir(exist_ok=True)
names = sorted(p.stem for p in (RES / "test").glob("t1_lexicon__*.parquet"))
rep = {}

# 1. agreement
ag = agreement(names)
for dim, m in ag.items():
    m.index = m.columns = [c.split("__")[1] for c in m.columns]
    rep[f"agreement_{dim}"] = m
    print(f"\n== agreement {dim}\n", m.to_string())

# features for the checks
c = ["id", "source", "date", "nrc_hit_count_log", "nrc_V_mean", "nrc_A_mean", "exclamation_density",
     "question_density", "ctx_high_arousal_fraction", "negation_word_fraction", "uppercase_word_fraction",
     "repeated_punctuation_density", "log_n_words"]
d = pd.concat([load("x_train_final", c), load("x_test_final", c)])
d["n"] = np.expm1(d["nrc_hit_count_log"]).round()
d["year"] = pd.to_datetime(d["date"], errors="coerce").dt.year

# 2. noise vs length
bins = [0, 1, 2, 5, 10, 20, 50, 100, 500]
d["nbin"] = pd.cut(d["n"], bins, include_lowest=True)
spread = d[d.n > 0].groupby("nbin", observed=True)[["nrc_V_mean", "nrc_A_mean"]].std()
rep["spread_by_n"] = spread
fig, ax = plt.subplots(figsize=(6, 3.5))
spread.plot(kind="bar", ax=ax)
ax.set_ylabel("std of speech score"); ax.set_xlabel("matched lexicon words"); ax.set_title("Short speeches = noisy scores")
fig.tight_layout(); fig.savefig(OUT / "noise_vs_length.png", dpi=120); plt.close(fig)

# 3. sanity correlations (Spearman, speeches with >= 5 matched words)
s = d[d.n >= 5]
cues = ["exclamation_density", "question_density", "ctx_high_arousal_fraction", "negation_word_fraction",
        "uppercase_word_fraction", "repeated_punctuation_density", "log_n_words"]
sanity = pd.DataFrame({t: [s[t].corr(s[cu], method="spearman") for cu in cues] for t in ["nrc_V_mean", "nrc_A_mean"]},
                      index=cues).round(3)
rep["sanity_spearman"] = sanity
print("\n== sanity (Spearman, n>=5)\n", sanity.to_string())

# 4. per parliament / per year
by_src = d[d.n >= 5].groupby("source")[["nrc_V_mean", "nrc_A_mean"]].mean().round(4)
rep["by_source"] = by_src
yr = d[d.n >= 5].groupby(["year", "source"])[["nrc_V_mean", "nrc_A_mean"]].mean().unstack("source")
fig, axs = plt.subplots(1, 2, figsize=(11, 3.5))
for ax, dim, lab in zip(axs, ["nrc_V_mean", "nrc_A_mean"], ["valence", "arousal"]):
    yr[dim].plot(ax=ax); ax.set_title(f"Mean {lab} per year"); ax.set_xlabel("")
fig.tight_layout(); fig.savefig(OUT / "per_year.png", dpi=120); plt.close(fig)

# 5. valence vs arousal (U-shape?)
vb = pd.cut(s["nrc_V_mean"], np.linspace(0.3, 0.85, 23))
u = s.groupby(vb, observed=True)["nrc_A_mean"].agg(["mean", "size"])
u = u[u["size"] >= 200]
rep["arousal_by_valence"] = u.round(4)
fig, ax = plt.subplots(figsize=(6, 3.5))
ax.plot([iv.mid for iv in u.index], u["mean"], marker="o")
ax.set_xlabel("valence (nrc_V_mean)"); ax.set_ylabel("mean arousal"); ax.set_title("Arousal vs valence")
fig.tight_layout(); fig.savefig(OUT / "arousal_vs_valence.png", dpi=120); plt.close(fig)

# distributions of the variants
fig, axs = plt.subplots(1, 2, figsize=(11, 3.5))
for nm in ["raw_mean", "median", "eb_global"]:
    p = pd.read_parquet(RES / "test" / f"t1_lexicon__{nm}.parquet")
    for ax, dim in zip(axs, ["valence", "arousal"]):
        ax.hist(p[dim], bins=120, range=(0.2, 0.9), histtype="step", label=nm, density=True)
for ax, dim in zip(axs, ["valence", "arousal"]):
    ax.set_title(dim); ax.legend()
fig.tight_layout(); fig.savefig(OUT / "distributions.png", dpi=120); plt.close(fig)

# 6. Italian set
it_path = Path(__file__).resolve().parents[2] / "data" / "processed" / "x_Italia.parquet"
if it_path.exists():
    it = pd.read_parquet(it_path, columns=["nrc_V_mean", "nrc_A_mean"])
    rep["italia_vs_test"] = pd.DataFrame({"italia": it.mean(), "test": d[["nrc_V_mean", "nrc_A_mean"]].mean()}).round(4)

with open(Path(__file__).parent / "checks_report.md", "w") as f:
    f.write("# t1_lexicon checks (generated by checks.py)\n\n")
    for k, v in rep.items():
        f.write(f"## {k}\n\n```\n{v.to_string()}\n```\n\n")
print("\nfigures in", OUT)
